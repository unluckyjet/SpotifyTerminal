import {test,expect} from 'bun:test';
import {SessionStats} from './session-stats';
const hear=(id:string,playing:boolean,position:number,duration=200)=>({id,playing,position,duration});
test('session stats count tracks, playing seconds, and skips',()=>{
  const stats=new SessionStats(0);
  expect(stats.snapshot(0)).toEqual({tracks:0,seconds:0,skips:0,startedAt:0});
  expect(stats.format(0)).toBe('0 tracks · 0:00 · 0 skips');
  stats.observe(hear('a',true,10),0);
  expect(stats.snapshot(0)).toEqual({tracks:1,seconds:0,skips:0,startedAt:0});
  expect(stats.format(0)).toBe('1 track · 0:00 · 0 skips');
  stats.observe(hear('a',true,12),2000);
  expect(stats.snapshot(2000).seconds).toBe(2);
  expect(stats.snapshot(3500).seconds).toBe(3);
  expect(stats.snapshot(3500).seconds).toBe(3);
  stats.observe(hear('a',true,13),4000);
  expect(stats.snapshot(4000).seconds).toBe(4);
  stats.observe(hear('a',false,14),5000);
  stats.observe(hear('a',false,5),10_000);
  expect(stats.snapshot(10_000).seconds).toBe(5);
  expect(stats.snapshot(10_000).skips).toBe(0);
  stats.observe(hear('a',true,14),11_000);
  stats.observe(hear('a',true,16),13_000);
  expect(stats.snapshot(13_000).seconds).toBe(7);
  stats.observe(hear('a',true,20),20_000);
  expect(stats.snapshot(20_000).seconds).toBe(12);
  stats.observe(hear('a',true,21),19_000);
  expect(stats.snapshot(19_000).seconds).toBe(12);
  stats.observe(hear('b',true,0,100),19_000);
  expect(stats.snapshot(19_000)).toEqual({tracks:2,seconds:12,skips:1,startedAt:0});
  stats.observe(hear('b',true,80,100),20_000);
  stats.observe(hear('c',true,0,180),21_000);
  expect(stats.snapshot(21_000).tracks).toBe(3);
  expect(stats.snapshot(21_000).skips).toBe(1);
  stats.observe(hear('c',true,40,180),22_000);
  stats.observe(hear('c',true,5,180),23_000);
  expect(stats.snapshot(23_000).skips).toBe(2);
  expect(stats.format(23_000)).toBe('3 tracks · 0:16 · 2 skips');
  const paused=new SessionStats(0);
  paused.observe(hear('x',false,10),0);
  paused.observe(hear('y',true,0),4000);
  expect(paused.snapshot(4000)).toEqual({tracks:2,seconds:0,skips:0,startedAt:0});
  expect(paused.snapshot(20_000).seconds).toBe(5);
});
test('format matches live session copy and floors fractional seconds',()=>{
  const stats=new SessionStats(0);
  stats.observe(hear('a',true,0,1000),0);
  for(let i=1;i<=181;i++)stats.observe(hear('a',true,i,1000),i*4000);
  stats.observe(hear('b',true,0,100),724_000);
  stats.observe(hear('b',true,80,100),724_000);
  stats.observe(hear('c',true,0,100),724_000);
  expect(stats.snapshot(724_000)).toEqual({tracks:3,seconds:724,skips:1,startedAt:0});
  expect(stats.format(724_000)).toBe('3 tracks · 12:04 · 1 skip');
  const partial=new SessionStats(0);
  partial.observe(hear('z',true,0),0);
  partial.observe(hear('z',true,1),2500);
  expect(partial.snapshot(2500).seconds).toBe(2);
  expect(partial.format(2500)).toBe('1 track · 0:02 · 0 skips');
});
